CREATE DATABASE IF NOT EXISTS hospital_analytics_db;
USE hospital_analytics_db;

DROP TABLE IF EXISTS visits;
DROP TABLE IF EXISTS patients;
DROP TABLE IF EXISTS departments;

-- 1. Departments Table
CREATE TABLE departments (
    department_id INT PRIMARY KEY AUTO_INCREMENT,
    department_name VARCHAR(100) NOT NULL UNIQUE
);

-- 2. Patients Table (Strictly De-identified: No Name, No Phone, No Address, No Exact DOB)
CREATE TABLE patients (
    patient_id INT PRIMARY KEY AUTO_INCREMENT,
    age_band VARCHAR(20) NOT NULL CHECK (age_band IN ('0-17', '18-34', '35-49', '50-64', '65+')),
    gender_optional VARCHAR(20) DEFAULT 'Unspecified' CHECK (gender_optional IN ('Female', 'Male', 'Other', 'Unspecified'))
);

-- 3. Visits Table (Operational Visit & Appointment Logs)
CREATE TABLE visits (
    visit_id INT PRIMARY KEY AUTO_INCREMENT,
    patient_id INT NOT NULL,
    department_id INT NOT NULL,
    visit_date DATE NOT NULL,
    visit_type VARCHAR(30) NOT NULL CHECK (visit_type IN ('Outpatient', 'Emergency', 'Follow-up', 'Inpatient')),
    CONSTRAINT fk_visits_patient FOREIGN KEY (patient_id) REFERENCES patients(patient_id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_visits_department FOREIGN KEY (department_id) REFERENCES departments(department_id) ON DELETE RESTRICT ON UPDATE CASCADE,
    INDEX idx_visit_date (visit_date),
    INDEX idx_dept_date (department_id, visit_date)
);

